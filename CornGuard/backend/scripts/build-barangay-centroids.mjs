// Generates convex/lib/barangayCentroids.ts from the app's bundled Bukidnon boundaries, so the
// public map can show an approximate per-barangay point instead of a report's exact farm
// coordinates (remediation for the mapReports privacy finding — see docs/OUTBREAK_DETECTION_METHOD.md
// sibling note in the map-privacy fix commit).
//
//   node scripts/build-barangay-centroids.mjs
//
// The centroid is the plain average of each polygon's outer-ring vertices (a vertex centroid, not
// an area-weighted one). That is intentionally approximate: this table exists to coarsen a
// location, not to pinpoint one, so survey-grade precision is not the goal.

import { readFileSync, writeFileSync } from "node:fs";

const geo = JSON.parse(readFileSync(
  new URL("../../android/app/src/main/assets/geo/bukidnon-barangays.json", import.meta.url), "utf8"));

const entries = geo.features.map((f) => {
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  const pts = polys.map((p) => p[0]).flat(); // outer rings only
  const lng = pts.reduce((sum, p) => sum + p[0], 0) / pts.length;
  const lat = pts.reduce((sum, p) => sum + p[1], 0) / pts.length;
  return [`${f.properties.barangay}||${f.properties.municipality}`, { lat, lng }];
});
entries.sort(([a], [b]) => a.localeCompare(b));

const body = entries
  .map(([key, { lat, lng }]) => `  ${JSON.stringify(key)}: { lat: ${lat.toFixed(6)}, lng: ${lng.toFixed(6)} },`)
  .join("\n");

const out = `// GENERATED by scripts/build-barangay-centroids.mjs from the app's bukidnon-barangays.json.
// Do not edit by hand; re-run the script if the boundaries change.
// Key is "barangay||municipality", exactly as in the boundary file (same convention as
// barangayNeighbors.ts). Each value is a vertex-average centroid of that barangay's polygon —
// an approximate point, used to coarsen a report's location for viewers who aren't its owner
// or an admin (see lib/mapPrivacy.ts).

export const BARANGAY_CENTROIDS: Record<string, { lat: number; lng: number }> = {
${body}
};
`;

writeFileSync(new URL("../convex/lib/barangayCentroids.ts", import.meta.url), out);
console.log(`Wrote ${entries.length} barangay centroids to convex/lib/barangayCentroids.ts`);
