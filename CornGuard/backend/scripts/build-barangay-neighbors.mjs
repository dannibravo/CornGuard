// Generates convex/barangayNeighbors.ts from the app's bundled Bukidnon boundaries, so outbreak
// alerts reach the barangay and the ones bordering it (caps 3 used a hand-written table of ~15
// barangays keyed by name only; this covers all 464 and keeps municipalities apart).
//
//   node scripts/build-barangay-neighbors.mjs
//
// Two barangays are neighbours when their borders come within EPS degrees of each other. The
// boundaries are simplified at 0.005°, so shared borders don't line up exactly.

import { readFileSync, writeFileSync } from "node:fs";

const EPS = 0.004; // ≈ 440 m

const geo = JSON.parse(readFileSync(
  new URL("../../android/app/src/main/assets/geo/bukidnon-barangays.json", import.meta.url), "utf8"));

const areas = geo.features.map((f) => {
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  const rings = polys.map((p) => p[0]); // outer rings only
  const pts = rings.flat();
  const xs = pts.map((p) => p[0]), ys = pts.map((p) => p[1]);
  return {
    key: `${f.properties.barangay}||${f.properties.municipality}`,
    rings,
    box: [Math.min(...xs) - EPS, Math.min(...ys) - EPS, Math.max(...xs) + EPS, Math.max(...ys) + EPS],
  };
});

const boxesTouch = (a, b) => a[0] <= b[2] && b[0] <= a[2] && a[1] <= b[3] && b[1] <= a[3];

function pointSegDist([px, py], [ax, ay], [bx, by]) {
  const dx = bx - ax, dy = by - ay;
  const len = dx * dx + dy * dy;
  const t = len === 0 ? 0 : Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / len));
  return Math.hypot(px - (ax + t * dx), py - (ay + t * dy));
}

function near(a, b) {
  for (const ra of a.rings) for (const p of ra) {
    for (const rb of b.rings) for (let i = 1; i < rb.length; i++) {
      if (pointSegDist(p, rb[i - 1], rb[i]) < EPS) return true;
    }
  }
  return false;
}

const neighbors = Object.fromEntries(areas.map((a) => [a.key, []]));
for (let i = 0; i < areas.length; i++) {
  for (let j = i + 1; j < areas.length; j++) {
    const a = areas[i], b = areas[j];
    if (!boxesTouch(a.box, b.box)) continue;
    if (near(a, b) || near(b, a)) {
      neighbors[a.key].push(b.key);
      neighbors[b.key].push(a.key);
    }
  }
}

const counts = Object.values(neighbors).map((n) => n.length);
const isolated = Object.entries(neighbors).filter(([, n]) => n.length === 0).map(([k]) => k);
console.log(`${areas.length} barangays; neighbours min ${Math.min(...counts)}, ` +
  `avg ${(counts.reduce((s, c) => s + c, 0) / counts.length).toFixed(1)}, max ${Math.max(...counts)}`);
if (isolated.length) console.log(`no neighbours: ${isolated.join(", ")}`);

const body = Object.entries(neighbors)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([k, n]) => `  ${JSON.stringify(k)}: ${JSON.stringify(n.sort())},`)
  .join("\n");

writeFileSync(new URL("../convex/barangayNeighbors.ts", import.meta.url),
`// GENERATED by scripts/build-barangay-neighbors.mjs from the app's bukidnon-barangays.json.
// Do not edit by hand; re-run the script if the boundaries change.
// Key and values are "barangay||municipality", exactly as in the boundary file.

export const BARANGAY_NEIGHBORS: Record<string, string[]> = {
${body}
};
`);
console.log("wrote convex/barangayNeighbors.ts");
